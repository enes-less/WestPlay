import type { Strings } from '.'

const RULES = new Intl.PluralRules('sr-Cyrl-RS')

/** The word for `n` by Serbian's plural forms: 1 песма, 2 песме, 5 песама. */
const forms = (n: number, one: string, few: string, other: string) => {
  const rule = RULES.select(n)
  return rule === 'one' ? one : rule === 'few' ? few : other
}

/** A count as text ("1.234.567", or YouTube's "1.2M"): its number when it's a whole one, for its word's form. */
