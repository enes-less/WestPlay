import type { Strings } from '.'

const RULES = new Intl.PluralRules('hr-HR')

/** A count's word by Croatian's plural forms: 1 pjesma, 2 pjesme, 5 pjesama (21 pjesma, 11 pjesama). */
const plural = (n: number, one: string, few: string, other: string) => {
  const form = RULES.select(n)
  return form === 'one' ? one : form === 'few' ? few : other
}

/** The number in a count written out ("1.234.567"); `null` for a shortened one ("1,2 mil."), which takes the
 * genitive plural. */
const countIn = (text: string) => (/^[\d\s.,  ]+$/.test(text) ? Number(text.replace(/\D/g, '')) : null)

