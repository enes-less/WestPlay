import type { Strings } from '.'

const RULES = new Intl.PluralRules('uk-UA')

/** The word for `n` by Ukrainian's plural forms: 1 трек, 2 треки, 5 треків (a fraction takes the second). */
const forms = (n: number, one: string, few: string, many: string) => {
  const rule = RULES.select(n)
  return rule === 'one' ? one : rule === 'many' ? many : few
}

/** A count as text ("1 234 567", or YouTube's "1.2M"): its number when it's a whole one, for its word's form. */
