import type { Strings } from '.'

const RULES = new Intl.PluralRules('lt-LT')

/** A count's word by Lithuanian's plural forms: 1 daina, 2 dainos, 10 dainų (21 daina, 22 dainos, 11 dainų). */
const plural = (n: number, one: string, few: string, other: string) => {
  const form = RULES.select(n)
  return form === 'one' ? one : form === 'few' || form === 'many' ? few : other
}

/** The number in a count written out ("1 234 567"); `null` for a shortened one ("1,2 mln."), which takes the
 * genitive plural. */
const countIn = (text: string) => (/^[\d\s.,  ]+$/.test(text) ? Number(text.replace(/\D/g, '')) : null)

