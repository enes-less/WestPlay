/** A count's word: the nominative after 1, the partitive after any other number (1 kappale, 5 kappaletta). */
const plural = (n: number, one: string, other: string) => (n === 1 ? one : other)

/** The number in a count written out ("1 234 567"); `null` for a shortened one ("1,2 milj."), which takes the
 * partitive. */
