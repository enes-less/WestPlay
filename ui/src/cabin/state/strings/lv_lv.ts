const RULES = new Intl.PluralRules('lv-LV')

/** A count's word by Latvian's plural forms: 1 dziesma, 21 dziesma, but 2, 10 and 11 dziesmas. */
const plural = (n: number, one: string, other: string) => (RULES.select(n) === 'one' ? one : other)

/** The number in a count written out ("1 234 567"); `null` for a shortened one ("1,2 milj."), which takes the
 * genitive plural. */
const countIn = (text: string) => (/^[\d\s.,  ]+$/.test(text) ? Number(text.replace(/\D/g, '')) : null)

