import type { Strings } from '.'

const PLURAL = new Intl.PluralRules('sk-SK')

/** `n` with its noun in the form Slovak takes after it: 1 skladba, 2 skladby, 5 skladieb. */
const count = (n: number, one: string, few: string, many: string) => {
  const form = PLURAL.select(n)
  return `${n} ${form === 'one' ? one : form === 'few' ? few : many}`
}

/** A count YouTube or Spotify wrote out ("1 234 567", "1.2M"): its noun's form by the whole number in it. */
const countIn = (text: string, one: string, few: string, many: string) => {
  const n = /^[\d\s ]+$/.test(text) ? Number(text.replace(/\D/g, '')) : NaN
  return `${text} ${n === 1 ? one : n >= 2 && n <= 4 ? few : many}`
}

