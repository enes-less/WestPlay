import type { Strings } from '.'

const RULES = new Intl.PluralRules('sl-SI')

/** A count's word by Slovenian's plural forms: 1 skladba, 2 skladbi, 3 skladbe, 5 skladb (101 skladba). */
const plural = (n: number, one: string, two: string, few: string, other: string) => {
  const form = RULES.select(n)
  return form === 'one' ? one : form === 'two' ? two : form === 'few' ? few : other
}

/** The number in a count written out ("1.234.567"); `null` for a shortened one ("1,2 mio."), which takes the
 * genitive plural. */
const countIn = (text: string) => (/^[\d\s.,  ]+$/.test(text) ? Number(text.replace(/\D/g, '')) : null)

