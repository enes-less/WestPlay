import type { Strings } from '.'

const PLURAL = new Intl.PluralRules('ro-RO')

/** "1 melodie", "5 melodii", "20 de melodii": from 20 on (but not 101–119, 201–219…), Romanian puts "de"
 * between a count and its noun. */
function count(n: number, one: string, many: string): string {
  if (n === 1) return `1 ${one}`
  return `${n} ${PLURAL.select(n) === 'other' ? 'de ' : ''}${many}`
}

/** The "de " a count already written out ("1.234.567", "1,2 mil.") takes before its noun. */
function de(written: string): string {
  if (/[^\d\s.,]/.test(written)) return 'de '
  return PLURAL.select(Number(written.replace(/\D/g, ''))) === 'other' ? 'de ' : ''
}

